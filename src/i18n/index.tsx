export const MESSAGES = { en: EN as Record<Key, string>, te: TE } as const;

export function translate(key: Key, lang: Lang): string {
  return (lang === "te" ? TE[key] : undefined) || EN[key];
}

/** Keep the document head in step with the language: title, description, Open Graph, Twitter, hreflang. */
function syncHead(lang: Lang): void {
  if (typeof document === "undefined") return;
  const title = translate("meta.title", lang), desc = translate("meta.description", lang);
  document.title = title;
  const meta = (sel: string, attr: string, val: string) => {
    const el = document.head.querySelector(sel);
    if (el) el.setAttribute(attr, val);
  };
  meta('meta[name="description"]', "content", desc);
  meta('meta[property="og:title"]', "content", title);
  meta('meta[property="og:description"]', "content", desc);
  meta('meta[property="og:locale"]', "content", translate("meta.locale", lang));
  meta('meta[property="og:locale:alternate"]', "content", translate("meta.locale", lang === "te" ? "en" : "te"));
  meta('meta[name="twitter:title"]', "content", title);
  meta('meta[name="twitter:description"]', "content", desc);
  // hreflang needs absolute URLs, so these are built from the live origin (production should also set a fixed canonical).
  const base = window.location.origin + window.location.pathname;
  document.head.querySelectorAll("link[data-pp-alt]").forEach((n) => n.remove());
  for (const [code, q] of [["en", "?lang=en"], ["te", "?lang=te"], ["x-default", ""]] as const) {
    const l = document.createElement("link");
    l.rel = "alternate"; l.hreflang = code; l.href = base + q; l.setAttribute("data-pp-alt", "1");
    document.head.appendChild(l);
  }
}

interface Ctx { lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => string }
const LangCtx = createContext<Ctx | null>(null);

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      const q = new URLSearchParams(window.location.search).get("lang"); // shared hreflang links win over the saved choice
      if (q === "te" || q === "en") return q;
    } catch { /* ignore */ }
    try { return localStorage.getItem(KEY) === "te" ? "te" : "en"; } catch { return "en"; }
  });
  useEffect(() => {
    try { localStorage.setItem(KEY, lang); } catch { /* ignore */ }
    document.documentElement.lang = lang;
    syncHead(lang);
  }, [lang]);
  const t = useCallback((k: Key) => translate(k, lang), [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, t]);
  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export function useT(): Ctx {
  const c = useContext(LangCtx);
  if (!c) throw new Error("useT outside LangProvider");
  return c;
}
