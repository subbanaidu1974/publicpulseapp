export type ScopeKey = keyof typeof EN;

export function useScopeT(): (key: ScopeKey, vars?: Record<string, string | number>) => string {
  const { lang } = useT();
  return (key, vars) => {
    let v: string = (lang === "te" ? TE : EN)[key] ?? EN[key] ?? key;
    if (vars) for (const [k, x] of Object.entries(vars)) v = v.replace(`{${k}}`, String(x));
    return v;
  };
}
