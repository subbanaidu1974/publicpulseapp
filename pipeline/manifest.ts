/**
 * Dataset manifest: one entry per shipped data file (generated snapshots plus the hand-curated reference files) with
 * source URLs, licence keys (resolved against data/reference/licences.json), checksum, as-of date, row counts and
 * attribution text. API envelopes read `source` and `asOf` from it; `pipeline:validate` fails on any mismatch.
 */

export interface ManifestEntry {
  id: string;
  /** repo-relative path with forward slashes */
  path: string;
  bytes: number;
  /** sha256 of the file content with CRLF normalised to LF (stable across git autocrlf checkouts) */
  sha256: string;
  rows: number;
  asOf: string | null;
  provenance: string;
  demo: boolean;
  sources: string[];
  licences: string[];
  attribution: string;
}
export interface Manifest { schema: 1; datasets: ManifestEntry[] }

