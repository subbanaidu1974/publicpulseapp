export function sha256Of(path: string): string {
  const text = readFileSync(path).toString("latin1").replace(/\r\n/g, "\n");
  return createHash("sha256").update(Buffer.from(text, "latin1")).digest("hex");
}

function walk(dir: string, base = dir): string[] {
  const out: string[] = [];
  for (const n of readdirSync(dir).sort()) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) out.push(...walk(p, base));
    else out.push(relative(base, p).split("\\").join("/"));
  }
  return out;
}

const ROW_KEYS = ["results", "districts", "subDistricts", "units", "rows", "features", "records", "parties", "villages", "sets"];
function summarise(json: unknown): { rows: number; asOf: string | null; provenance: string | null } {
  if (Array.isArray(json)) return { rows: json.length, asOf: null, provenance: null };
  const o = (json ?? {}) as Record<string, unknown>;
  const key = ROW_KEYS.find(k => Array.isArray(o[k]));
  const asOf = typeof o.asOf === "string" ? o.asOf : null;
  const provenance = typeof o.provenance === "string" ? o.provenance : typeof o.generator === "string" ? o.generator : null;
  return { rows: key ? (o[key] as unknown[]).length : Object.keys(o).length, asOf, provenance };
}

/** Build the manifest for a generated-data directory (default data/generated) plus the reference files under `root`. */
export function buildManifest(genDir: string = GENERATED, root: string = ROOT): Manifest {
  const datasets: ManifestEntry[] = [];
  for (const rel of walk(genDir)) {
    if (rel === MANIFEST_NAME || !rel.endsWith(".json") && !rel.endsWith(".geojson")) continue;
    const rule = RULES.find(r => r.match.test(rel));
    const abs = resolve(genDir, rel);
    const json = JSON.parse(readFileSync(abs, "utf8"));
    const s = summarise(json);
    const prov = (rule?.id(rel) === "elections" && typeof json.provenance === "string") ? json.provenance : s.provenance;
    const maxYear = rule?.id(rel) === "elections" && Array.isArray(json.results) ? String(Math.max(...json.results.map((r: { year: number }) => r.year))) : null;
    datasets.push({
      id: rule ? rule.id(rel) : `unclassified-${rel.replace(/[^a-z0-9]+/gi, "-")}`,
      path: `data/generated/${rel}`,
      bytes: statSync(abs).size,
      sha256: sha256Of(abs),
      rows: s.rows,
      asOf: s.asOf ?? rule?.asOf ?? (maxYear ? `${maxYear} (latest election in file)` : null),
      provenance: prov ?? "unknown",
      demo: s.provenance === "demo" || json.provenance === "demo",
      sources: rule?.sources ?? [],
      licences: rule?.licences ?? ["project-derived"],
      attribution: rule?.attribution ?? "Unclassified dataset: add a rule in pipeline/manifest.ts.",
    });
  }
  for (const rel of REFERENCE_FILES) {
    const abs = resolve(root, rel);
    if (!existsSync(abs)) continue;
    const json = JSON.parse(readFileSync(abs, "utf8"));
    const s = summarise(json);
    const r = REF_RULES[rel];
    datasets.push({
      id: rel.includes("parties") ? "parties" : "alliances", path: rel, bytes: statSync(abs).size, sha256: sha256Of(abs), rows: s.rows,
      asOf: s.asOf, provenance: "hand-curated", demo: false, ...r,
    });
  }
  datasets.sort((a, b) => a.id.localeCompare(b.id));
  return { schema: 1, datasets };
}

export function writeManifest(genDir: string = GENERATED, root: string = ROOT): Manifest {
  const m = buildManifest(genDir, root);
  writeJson(resolve(genDir, MANIFEST_NAME), m);
  return m;
}

const fileFor = (genDir: string, root: string, path: string) =>
  path.startsWith("data/generated/") ? resolve(genDir, path.slice("data/generated/".length)) : resolve(root, path);

export function loadLicenceKeys(root: string = ROOT): string[] {
  const p = resolve(root, "data/reference/licences.json");
  return existsSync(p) ? Object.keys(JSON.parse(readFileSync(p, "utf8")).licences ?? {}) : [];
}

/**
 * Check a manifest against disk: every dataset file listed, checksums equal, licence keys registered.
 * `requireAll` also requires every file under genDir (and the reference files) to have an entry.
 */
export function verifyManifest(genDir: string = GENERATED, root: string = ROOT): string[] {
  const errs: string[] = [];
  const mp = resolve(genDir, MANIFEST_NAME);
  if (!existsSync(mp)) return [`${MANIFEST_NAME} missing (run npm run pipeline:manifest)`];
  const m = JSON.parse(readFileSync(mp, "utf8")) as Manifest;
  const keys = new Set(loadLicenceKeys(root));
  const listed = new Set<string>();
  for (const d of m.datasets) {
    listed.add(d.path);
    const f = fileFor(genDir, root, d.path);
    if (!existsSync(f)) { errs.push(`manifest: ${d.path} listed but missing on disk`); continue; }
    if (sha256Of(f) !== d.sha256) errs.push(`manifest: checksum mismatch for ${d.path} (re-run pipeline:manifest after regenerating data)`);
    if (!d.licences?.length) errs.push(`manifest: ${d.id} has no licence key`);
    for (const k of d.licences ?? []) if (!keys.has(k)) errs.push(`manifest: ${d.id} uses licence key '${k}' that is not in data/reference/licences.json`);
    if (!d.sources?.length && d.provenance !== "hand-curated") errs.push(`manifest: ${d.id} has no source URL`);
  }
  for (const rel of walk(genDir)) {
    if (rel === MANIFEST_NAME || !rel.endsWith(".json") && !rel.endsWith(".geojson")) continue;
    if (!listed.has(`data/generated/${rel}`)) errs.push(`manifest: data/generated/${rel} has no manifest entry`);
  }
  for (const rel of REFERENCE_FILES) if (existsSync(resolve(root, rel)) && !listed.has(rel)) errs.push(`manifest: ${rel} has no manifest entry`);
  return errs;
}

/** NC / SA / do-not-ship constraints used by shipped datasets, for the human-decision list. */
export function licenceDecisions(root: string = ROOT, genDir: string = GENERATED): { key: string; status: string; constraints: string[]; decision: string; datasets: string[] }[] {
  const reg = JSON.parse(readFileSync(resolve(root, "data/reference/licences.json"), "utf8")).licences as Record<string, { status: string; constraints: string[]; needsDecision: boolean; decision?: string }>;
  const m = existsSync(resolve(genDir, MANIFEST_NAME)) ? (JSON.parse(readFileSync(resolve(genDir, MANIFEST_NAME), "utf8")) as Manifest) : { datasets: [] as ManifestEntry[] };
  return Object.entries(reg).filter(([, v]) => v.needsDecision).map(([key, v]) => ({
    key, status: v.status, constraints: v.constraints, decision: v.decision ?? "", datasets: m.datasets.filter(d => d.licences.includes(key)).map(d => d.id),
  }));
}
