/** Generates docs/ATTRIBUTION.md from data/reference/licences.json, data/generated/manifest.json and the party media in parties.json. */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { ROOT } from "../pipeline/io";
import { licenceDecisions, buildManifest } from "../pipeline/manifest";
import { GENERATED } from "../pipeline/io";

export function renderAttribution(root: string = ROOT, genDir: string = GENERATED): string {
  const reg = JSON.parse(readFileSync(resolve(root, "data/reference/licences.json"), "utf8"));
  const parties = JSON.parse(readFileSync(resolve(root, "data/reference/parties.json"), "utf8"));
  const manifest = buildManifest(genDir, root);
  const L: string[] = [];
  L.push("# Data attribution and licence register", "");
  L.push("Generated by `npm run pipeline:attribution` from `data/reference/licences.json`, the dataset manifest and `data/reference/parties.json`. Do not edit by hand.", "");
  L.push(`Register as of ${reg.asOf}. ${reg.disclaimer}`, "");
  L.push("## Datasets and the licences they rely on", "");
  L.push("| Dataset | As of | Licence keys | Attribution text |", "|---|---|---|---|");
  for (const d of manifest.datasets) L.push(`| ${d.id}${d.demo ? " (demo)" : ""} | ${d.asOf ?? "n/a"} | ${d.licences.join(", ")} | ${d.attribution.replace(/\|/g, "/")} |`);
  L.push("", "## Licence register", "");
  for (const [key, v] of Object.entries<any>(reg.licences)) {
    L.push(`### ${key}`, "", `- Name: ${v.name}`, ...(v.url ? [`- URL: ${v.url}`] : []), `- Status: ${v.status}`,
      `- Constraints: ${v.constraints.length ? v.constraints.join("; ") : "none beyond attribution"}`, `- Attribution: ${v.attribution}`,
      `- Evidence: ${v.evidence}`, ...(v.needsDecision ? [`- **Needs a human decision:** ${v.decision}`] : []), "");
  }
  L.push("## Constraints that need a human decision", "");
  for (const d of licenceDecisions(root, genDir)) {
    L.push(`- **${d.key}** (${d.status}; ${d.constraints.join(", ") || "no constraints"}) used by: ${d.datasets.join(", ") || "no shipped dataset"}. ${d.decision}`);
  }
  L.push("", "## Party flags and symbols (Wikimedia Commons)", "",
    "Files marked identification-only identify the party and must not imply endorsement. Licences were re-read from the Commons API on the date shown.", "",
    "| Party | File | Licence | Author | Use | Verified |", "|---|---|---|---|---|---|");
  for (const p of parties.parties) for (const kind of ["flag", "symbol"] as const) {
    const m = p[kind];
    if (m) L.push(`| ${p.code} ${kind} | [${m.commonsFile}](https://commons.wikimedia.org/wiki/File:${encodeURIComponent(m.commonsFile.replace(/ /g, "_"))}) | ${m.licence} | ${m.author} | ${m.use} | ${m.verified} |`);
  }
  L.push("", "Parties without a verified free file (for example YSRCP) are shown as a text chip.", "");
  return L.join("\n");
}

if (process.argv[1]?.split("\\").join("/").endsWith("scripts/gen-attribution.ts")) {
  const out = resolve(ROOT, "docs/ATTRIBUTION.md");
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, renderAttribution());
  console.log(`[attribution] wrote ${out}`);
}
