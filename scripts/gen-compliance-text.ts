/**
 * Extracts the exact EN/TE text of every user-facing legal artefact into docs/compliance/ARTEFACT_TEXT.md (S-150).
 * Usage: tsx scripts/gen-compliance-text.ts [--check]   (--check exits 1 if the committed file is stale)
 * Read-only on source files; never edits the artefacts themselves.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PRIVACY, TERMS, WHO_SEES, ROLES, ROLE_LABELS } from "../src/i18n/content";

interface Artefact { id: string; name: string; kind: string; path: string; export?: string; textPath?: string; status: string; textSource: string }
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p: string) => fs.readFileSync(path.join(root, p), "utf8");

/** All `"key": "value"` string pairs in a TS source, in order; the first hit is EN, the second TE (two dictionaries). */
function pairs(src: string, prefix: string): Map<string, string[]> {
  const out = new Map<string, string[]>();
  for (const m of src.matchAll(/"([\w.]+)":\s*"((?:[^"\\]|\\.)*)"/g)) {
    if (!m[1].startsWith(prefix)) continue;
    out.set(m[1], [...(out.get(m[1]) ?? []), m[2]]);
  }
  return out;
}
const biTable = (m: Map<string, string[]>) =>
  ["| key | EN | TE |", "|---|---|---|", ...[...m].map(([k, v]) => `| \`${k}\` | ${v[0] ?? ""} | ${v[1] ?? ""} |`)].join("\n");

export function render(): string {
  const index = JSON.parse(read("docs/compliance/artefacts.json")) as { artefacts: Artefact[] };
  const out: string[] = [
    "# Exact text of user-facing legal artefacts (generated)",
    "",
    "Generated by `tsx scripts/gen-compliance-text.ts`. Do not edit by hand. Every artefact below is **DRAFT**: not reviewed by counsel, and the Telugu is machine-assisted, not reviewed by a native-speaker linguist. See COUNSEL_PACK.md.",
    "",
  ];
  for (const a of index.artefacts) {
    out.push(`## ${a.id}. ${a.name}`, "", `- Status: **${a.status}**`, `- File: \`${a.path}\`${a.export ? ` (export \`${a.export}\`)` : ""}`, "");
    if (a.textSource === "json-notice") {
      const j = JSON.parse(read(a.path));
      out.push(`- Declared status field: ${j.status}`, `- Version: ${j.version}`, "", `**Title EN:** ${j.title.en}`, "", `**Title TE:** ${j.title.te}`, "", `**Text EN:** ${j.text.en}`, "", `**Text TE:** ${j.text.te}`, "");
    } else if (a.textSource === "json-grievance") {
      out.push("```json", JSON.stringify(JSON.parse(read(a.path)), null, 2), "```", "");
    } else if (a.textSource === "legal-sections") {
      const list = a.export === "PRIVACY" ? PRIVACY : TERMS;
      for (const s of list) out.push(`### ${s.id}`, "", `- Heading EN: ${s.h.en}`, `- Heading TE: ${s.h.te}`, `- Text EN: ${s.p.en}`, `- Text TE: ${s.p.te}`, "");
    } else if (a.textSource === "who-sees") {
      out.push(`Roles: ${ROLES.map((r) => `${ROLE_LABELS[r].en} / ${ROLE_LABELS[r].te}`).join("; ")}`, "");
      for (const row of WHO_SEES) {
        out.push(`### ${row.id}: ${row.label.en} / ${row.label.te}`, "");
        for (const r of ROLES) out.push(`- ${r}: EN ${row.cells[r].en} | TE ${row.cells[r].te}`);
        out.push("");
      }
    } else if (a.textSource === "ppl-report") {
      out.push(biTable(pairs(read(a.path), "ppl.report.")), "");
    } else if (a.textSource === "civic-banner") {
      const m = pairs(read(a.textPath!), "c.");
      const keep = new Map([...m].filter(([k]) => ["c.draft", "c.version", "c.agree", "c.accept", "c.decline", "c.noticeFail"].includes(k)));
      out.push(biTable(keep), "");
    } else if (a.textSource === "legal-draft") {
      out.push(biTable(pairs(read(a.textPath!), "legal.draft")), "");
    } else {
      out.push("(Engineering document; the text lives in the file above.)", "");
    }
  }
  return out.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = path.join(root, "docs/compliance/ARTEFACT_TEXT.md");
  const text = render();
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== text) { console.error("docs/compliance/ARTEFACT_TEXT.md is stale; run tsx scripts/gen-compliance-text.ts"); process.exit(1); }
  } else { fs.writeFileSync(target, text); console.log("wrote", target); }
}
